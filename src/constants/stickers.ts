const STICKER_MAP = new Map(STICKERS.map((s) => [s.id, s.source]));

export const STICKER_PATTERN = /^\[sticker:(\d+)\]$/;

export function getStickerSource(id: number): ImageSourcePropType | null {
  return STICKER_MAP.get(id) ?? null;
}

export function isSticker(text: string): boolean {
  const match = text.trim().match(STICKER_PATTERN);
  if (!match) return false;
  return STICKER_MAP.has(parseInt(match[1], 10));
}

export function parseStickerText(text: string): number | null {
  const match = text.trim().match(STICKER_PATTERN);
  return match ? parseInt(match[1], 10) : null;
}
